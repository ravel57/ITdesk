package ru.ravel.ItDesk.model.incident;

/**
 * Что детектор решил по сообщению.
 */
public enum IncidentSignalDecision {
	/** Не похоже на сбой или сервис не определён — в подсчёт не идёт */
	IGNORED,
	/** Похоже на сбой, учтено в окне, порог ещё не достигнут */
	COUNTED,
	/** Относится к уже открытому инциденту */
	MATCHED_INCIDENT,
	/** Порог достигнут, пачка подтверждена: здесь создавался бы черновик инцидента */
	TRIGGERED,
	/** Порог достигнут, но Jev не подтвердил, что сообщения об одной проблеме */
	BATCH_REJECTED,
	/** Порог достигнут, но по этому сервису и симптому недавно уже было срабатывание */
	COOLDOWN
}
