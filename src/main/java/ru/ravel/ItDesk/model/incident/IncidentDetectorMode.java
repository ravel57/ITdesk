package ru.ravel.ItDesk.model.incident;

/**
 * Режим детектора массовых инцидентов Jev. В обоих режимах ответственные получают уведомление.
 */
public enum IncidentDetectorMode {
	/** При срабатывании ответственные получают уведомление, инцидент не создаётся */
	NOTIFY_ONLY,
	/** При срабатывании создаётся инцидент в статусе DRAFT, к нему привязываются заявки и следующие похожие обращения */
	CREATE_DRAFT
}
